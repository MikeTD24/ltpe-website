"""Generate SEO metadata for the currently published origin, without network access."""

import html
import json
import re
from pathlib import Path
from urllib.parse import urlparse
from xml.etree import ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
CONFIG = json.loads((ROOT / "scripts/seo.json").read_text(encoding="utf-8"))
BASE = CONFIG["base_url"]
assert BASE.endswith("/") and urlparse(BASE).scheme == "https"
LANGUAGES = ("fr", "nl", "en")
rows = []
urls = []


def page_url(filename, language):
    return f"{BASE}{filename}?lang={language}"


for filename, metadata in CONFIG["pages"].items():
    assert len(metadata["titles"]) == len(metadata["descriptions"]) == 3
    path = ROOT / filename
    source = path.read_text(encoding="utf-8")
    title = html.escape(metadata["titles"][0], quote=True)
    description = html.escape(metadata["descriptions"][0], quote=True)
    source = re.sub(r"<title>.*?</title>", f'<title data-no-translate>{title}</title>', source)
    source = re.sub(
        r'<meta\b(?=[^>]*\bname="description")[^>]*>',
        f'<meta name="description" content="{description}" data-no-translate />',
        source,
    )
    source = re.sub(r"\s*<!-- SEO BEGIN -->.*?<!-- SEO END -->", "", source, flags=re.S)
    tags = [
        "<!-- SEO BEGIN -->",
        f'<link rel="canonical" href="{page_url(filename, "fr")}" />',
    ]
    for language in LANGUAGES:
        url = page_url(filename, language)
        urls.append(url)
        tags.append(f'<link rel="alternate" hreflang="{language}" href="{url}" />')
    tags.extend([
        f'<link rel="alternate" hreflang="x-default" href="{page_url(filename, "fr")}" />',
        '<meta property="og:type" content="website" />',
        '<meta property="og:site_name" content="Le Temple du Plein Évangile" />',
        '<meta property="og:locale" content="fr_BE" />',
        f'<meta property="og:title" content="{title}" />',
        f'<meta property="og:description" content="{description}" />',
        f'<meta property="og:url" content="{page_url(filename, "fr")}" />',
        f'<meta property="og:image" content="{BASE}images/Ltpe-Temple.jpeg" />',
        '<meta name="twitter:card" content="summary_large_image" />',
        f'<meta name="twitter:title" content="{title}" />',
        f'<meta name="twitter:description" content="{description}" />',
        f'<meta name="twitter:image" content="{BASE}images/Ltpe-Temple.jpeg" />',
        '<script src="js/seo.js" defer></script>',
        "<!-- SEO END -->",
    ])
    block = "\n" + "\n".join("    " + tag for tag in tags) + "\n  </head>"
    source = re.sub(r"\s*</head>", lambda match: block, source, count=1)
    path.write_text(source, encoding="utf-8")
    rows.append([filename, metadata])

# An external script preserves the site's script-src 'self' policy.
runtime = """/* Generated by scripts/build-seo.py. Edit scripts/seo.json instead. */
(() => {
  'use strict';
  const pages = Object.fromEntries(__PAGES__);
  const languages = ['fr', 'nl', 'en'];
  const filename = location.pathname.split('/').pop() || 'index.html';
  const metadata = pages[filename];
  if (!metadata) return;

  function updateMetadata() {
    const language = window.ltpeI18n?.language || 'fr';
    const index = languages.indexOf(language);
    document.title = metadata.titles[index];
    const description = metadata.descriptions[index];
    document.querySelector('meta[name="description"]').content = description;
    const canonical = document.querySelector('link[rel="canonical"]');
    const url = new URL(canonical.href);
    url.searchParams.set('lang', language);
    canonical.href = url.href;
    const values = {
      'og:title': document.title,
      'og:description': description,
      'og:url': url.href,
      'og:locale': { fr: 'fr_BE', nl: 'nl_BE', en: 'en_GB' }[language],
    };
    for (const [property, value] of Object.entries(values)) {
      document.querySelector(`meta[property="${property}"]`).content = value;
    }
    document.querySelector('meta[name="twitter:title"]').content = document.title;
    document.querySelector('meta[name="twitter:description"]').content = description;
  }

  document.addEventListener('ltpe:languagechange', updateMetadata);
  updateMetadata();
})();
""".replace("__PAGES__", json.dumps(rows, ensure_ascii=False))
(ROOT / "js/seo.js").write_text(runtime, encoding="utf-8")

ET.register_namespace("", "http://www.sitemaps.org/schemas/sitemap/0.9")
namespace = "{http://www.sitemaps.org/schemas/sitemap/0.9}"
tree = ET.Element(namespace + "urlset")
for url in urls:
    item = ET.SubElement(tree, namespace + "url")
    ET.SubElement(item, namespace + "loc").text = url
ET.indent(tree, space="  ")
(ROOT / "sitemap.xml").write_bytes(ET.tostring(tree, encoding="utf-8", xml_declaration=True))
(ROOT / "robots.txt").write_text(
    f"User-agent: *\nAllow: /\n\nSitemap: {BASE}sitemap.xml\n", encoding="utf-8"
)
print(f"SEO generated: {len(rows)} pages, {len(urls)} language URLs, base {BASE}")
